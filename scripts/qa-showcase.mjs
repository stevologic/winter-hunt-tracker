import {chromium, expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
import {server} from './preview.mjs';
const out='website-qa';
await mkdir(out,{recursive:true});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const url=`http://127.0.0.1:${server.address().port}/`;
const browser=await chromium.launch({headless:true});
const newPage=async options=>(await browser.newContext(options)).newPage();
const report={checkedUtc:new Date().toISOString(),gameProcessesLaunched:false,checks:[],screenshots:[]};
const check=(name,data={})=>report.checks.push({name,...data});
try {
  const page=await newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>{
    window.__renders=0;
    const draw=WebGL2RenderingContext.prototype.drawElements;
    WebGL2RenderingContext.prototype.drawElements=function(...args){window.__renders++;return draw.apply(this,args);};
    window.__lcp=0;window.__cls=0;
    new PerformanceObserver(list=>{for(const e of list.getEntries())window.__lcp=e.startTime;}).observe({type:'largest-contentful-paint',buffered:true});
    new PerformanceObserver(list=>{for(const e of list.getEntries())if(!e.hadRecentInput)window.__cls+=e.value;}).observe({type:'layout-shift',buffered:true});
  });
  await page.goto(url);await page.locator('.camp-poster').evaluate(e=>e.decode());
  await page.waitForFunction(()=>window.__lcp>0);
  await expect(page.locator('#load-scene')).toBeVisible();
  const initial=await page.evaluate(()=>({resources:performance.getEntriesByType('resource').map(e=>e.name),bytes:performance.getEntriesByType('resource').reduce((s,e)=>s+e.encodedBodySize,0),lcpMs:window.__lcp,cls:window.__cls}));
  expect(initial.resources.some(x=>x.endsWith('.glb')||x.endsWith('/static/showcase.js'))).toBe(false);
  check('No 3D bundle/models requested before interaction',initial);
  await page.screenshot({path:`${out}/desktop-poster.png`,fullPage:true});report.screenshots.push('desktop-poster.png');
  const a11y=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  expect(a11y.violations).toEqual([]);check('Desktop WCAG AA automated checks',{violations:a11y.violations.length});
  const started=performance.now();await page.locator('#load-scene').click();
  await expect(page.locator('#camp-showcase')).toHaveAttribute('data-state','ready');
  const stats=await page.locator('#camp-showcase').evaluate(e=>({...e.dataset}));
  expect(+stats.drawCalls).toBeLessThanOrEqual(80);expect(+stats.triangles).toBeLessThan(20000);
  expect(+stats.renderWidth*+stats.renderHeight).toBeLessThanOrEqual(1200000);
  check('3D load and rendering budgets',{loadMs:Math.round(performance.now()-started),...stats});
  await expect(page.locator('#scene-motion')).toHaveAttribute('aria-pressed','false');
  const before=await page.evaluate(()=>window.__renders);await page.waitForTimeout(300);expect(await page.evaluate(()=>window.__renders)).toBe(before);
  check('No repeated draw calls while motion paused');
  await page.locator('#view-left').click();await expect(page.locator('#camp-showcase')).toHaveAttribute('data-state','ready');
  await page.locator('#view-reset').click();
  await page.locator('#scene-snow').click();await expect(page.locator('#scene-snow')).toHaveAttribute('aria-pressed','false');
  await page.locator('#scene-snow').click();
  await page.locator('#scene-motion').click();await expect(page.locator('#scene-motion')).toHaveAttribute('aria-pressed','true');
  const movingBefore=await page.evaluate(()=>window.__renders);await page.waitForTimeout(300);expect(await page.evaluate(()=>window.__renders)).toBeGreaterThan(movingBefore);
  await page.locator('#support').scrollIntoViewIfNeeded();await page.waitForTimeout(250);
  const offscreen=await page.evaluate(()=>window.__renders);await page.waitForTimeout(300);expect(await page.evaluate(()=>window.__renders)).toBe(offscreen);
  check('Motion enabled on request; rendering stops offscreen');
  await page.locator('#camp-showcase').scrollIntoViewIfNeeded();await page.locator('#scene-motion').click();
  await page.screenshot({path:`${out}/desktop-3d.png`,fullPage:true});report.screenshots.push('desktop-3d.png');
  await page.evaluate(()=>{window.__lose=document.querySelector('canvas').getContext('webgl2').getExtension('WEBGL_lose_context');window.__lose.loseContext();});
  await expect(page.locator('#camp-showcase')).toHaveAttribute('data-state','fallback');
  await expect(page.locator('#load-scene')).toBeVisible();
  await page.evaluate(()=>window.__lose.restoreContext());
  await expect(page.locator('#camp-showcase')).toHaveAttribute('data-state','ready');
  check('Actual WebGL context loss shows poster; restoration recovers');
  await page.getByRole('button',{name:'Reset view',exact:true}).focus();await page.keyboard.press('Tab');
  expect(await page.evaluate(()=>document.activeElement.getAttribute('aria-label'))).toBe('Look right');
  check('Keyboard-accessible scene controls');
  await page.locator('#copy-doge').scrollIntoViewIfNeeded();
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:async()=>{throw Error('Denied');}},configurable:true}));
  await page.locator('#copy-doge').click();await expect(page.locator('#copy-status')).toContainText('Select and copy');
  check('DOGE manual copy fallback');
  await page.close();
  for(const width of [390,320,768]) {
    const mobile=await newPage({viewport:{width,height:844},deviceScaleFactor:2,reducedMotion:'reduce'});
    await mobile.goto(url);await mobile.locator('.camp-poster').evaluate(e=>e.decode());
    expect(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    const result=await new AxeBuilder({page:mobile}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();expect(result.violations).toEqual([]);
    await mobile.screenshot({path:`${out}/mobile-${width}.png`,fullPage:true});report.screenshots.push(`mobile-${width}.png`);
    if(width===390) {
      await mobile.locator('#load-scene').click();await expect(mobile.locator('#camp-showcase')).toHaveAttribute('data-state','ready');
      await expect(mobile.locator('#scene-motion')).toHaveAttribute('aria-pressed','false');
      const dims=await mobile.locator('canvas').evaluate(e=>({width:e.width,height:e.height}));expect(dims.width*dims.height).toBeLessThanOrEqual(1200000);
      await mobile.screenshot({path:`${out}/mobile-3d.png`,fullPage:true});report.screenshots.push('mobile-3d.png');
      check('Reduced motion mobile3D starts paused and respects pixel cap',dims);
    }
    check(`Responsive ${width}px, no horizontal overflow, WCAG AA automated checks`);await mobile.close();
  }
  const nojs=await newPage({javaScriptEnabled:false,viewport:{width:390,height:844}});await nojs.goto(url);
  await expect(nojs.locator('.camp-poster')).toBeVisible();await expect(nojs.locator('#load-scene')).toBeHidden();
  expect(await nojs.getByRole('link',{name:/Request playtest access/}).count()).toBe(2);
  await nojs.screenshot({path:`${out}/no-javascript.png`,fullPage:true});report.screenshots.push('no-javascript.png');await nojs.close();check('No-JavaScript poster, gameplay and access links');
  const blocked=await newPage();await blocked.addInitScript(()=>{const get=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(kind,...args){if(kind==='webgl2')return null;return get.call(this,kind,...args);};});
  await blocked.goto(url);await blocked.locator('#load-scene').click();await expect(blocked.locator('#camp-showcase')).toHaveAttribute('data-state','fallback');await expect(blocked.locator('#scene-status')).toContainText('3D is unavailable');await blocked.close();check('WebGL-disabled fallback');
  const failed=await newPage();await failed.route('**/WH_CanvasTent.glb',route=>route.abort());await failed.goto(url);await failed.locator('#load-scene').click();await expect(failed.locator('#camp-showcase')).toHaveAttribute('data-state','fallback');
  await failed.unroute('**/WH_CanvasTent.glb');await failed.locator('#load-scene').click();await expect(failed.locator('#camp-showcase')).toHaveAttribute('data-state','ready');await failed.close();check('Model network failure cleans up; retry succeeds');
  const prefix=await newPage();await prefix.goto(url+'winter-hunt-tracker/');await prefix.locator('#load-scene').click();await expect(prefix.locator('#camp-showcase')).toHaveAttribute('data-state','ready');await prefix.close();check('GitHub Pages subpath loading');
  const slow=await newPage({viewport:{width:390,height:844}});
  await slow.addInitScript(()=>{window.__lcp=0;new PerformanceObserver(list=>{for(const e of list.getEntries())window.__lcp=e.startTime;}).observe({type:'largest-contentful-paint',buffered:true});});
  const cdp=await slow.context().newCDPSession(slow);
  await cdp.send('Network.enable');
  await cdp.send('Network.emulateNetworkConditions',{offline:false,latency:150,downloadThroughput:200000,uploadThroughput:90000,connectionType:'cellular3g'});
  await cdp.send('Emulation.setCPUThrottlingRate',{rate:4});
  await slow.goto(url);await slow.locator('.camp-poster').evaluate(e=>e.decode());await slow.waitForTimeout(250);
  check('Throttled first-render observation',{profile:'1.6 Mbps down, 150 ms RTT, 4x CPU; localhost Chromium, not real mobile hardware',...await slow.evaluate(()=>({lcpMs:window.__lcp,firstContentfulPaintMs:performance.getEntriesByName('first-contentful-paint')[0]?.startTime,resourceBytes:performance.getEntriesByType('resource').reduce((sum,e)=>sum+e.encodedBodySize,0)}))});
  await slow.close();
  expect(errors).toEqual([]);check('No uncaught runtime errors');
  const manifest=JSON.parse(await readFile('assets/showcase/provenance.json','utf8'));
  report.budget={modelsBytes:manifest.totalModelBytes,textureBytes:manifest.textures[0].bytes,posterBytes:(await readFile('assets/showcase/camp-poster.webp')).length,bundleBytes:(await readFile('static/showcase.js')).length,bundleGzipBytes:gzipSync(await readFile('static/showcase.js')).length};
  console.log(JSON.stringify({checks:report.checks.length,budget:report.budget}));
} finally {await writeFile(`${out}/receipt.json`,JSON.stringify(report,null,2)+'\n');await browser.close();await new Promise(resolve=>server.close(resolve));}
